//! Embeds the exact package bytes of the kernel's generic base Skills
//! (`contracts/kernel-skills.json`) as the single kernel Skill release.
//! Hosts install further Skills at runtime under their own product.
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

#[path = "../../../build-support/kernel_release.rs"]
mod kernel_release;
#[path = "../../../build-support/kernel_skills.rs"]
mod kernel_skills;

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("manifest directory"));
    let root = manifest_dir.join("../../..");
    let manifest = kernel_skills::load(&root);
    let digest = kernel_release::digest(&root);

    let mut generated = format!(
        "// @generated by crates/runtime/skill-release/build.rs; do not edit.\n\
         pub const OFFICIAL_SKILL_BUNDLE_REF: &str = {:?};\n\
         pub const OFFICIAL_SKILL_BUNDLE_RELEASED_AT_MS: i64 = {};\n\
         fn compiled_runtime_skill_release_specs() -> Vec<RuntimeSkillReleaseSpec> {{\n    vec![\n",
        manifest.bundle_ref, manifest.released_at_ms,
    );
    for skill in &manifest.skills {
        let (source, resources) = skill.files(&root);
        let resources = resources
            .iter()
            .map(|(archive, path)| {
                format!(
                    "RuntimeSkillReleaseResource {{ path: {archive:?}, bytes: include_bytes!({:?}) }}",
                    path.to_string_lossy()
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        let surfaces = skill
            .surfaces
            .iter()
            .map(|surface| format!("Surface::{}", kernel_skills::surface_variant(surface)))
            .collect::<Vec<_>>()
            .join(", ");
        write!(
            generated,
            "        RuntimeSkillReleaseSpec {{\n\
             skill_id: {:?}, skill_version_id: {:?}, key: {:?},\n\
             bundle_ref: {:?}, compatible_agent_contract: {:?},\n\
             version: {}, active: {}, supersedes: {:?},\n\
             identity_created_at_ms: {}, released_at_ms: {},\n\
             surfaces: &[{surfaces}],\n\
             sandbox: {},\n\
             instructions: include_bytes!({:?}),\n\
             resources: &[{resources}],\n\
             }},\n",
            skill.skill_id,
            skill.skill_version_id,
            skill.skill_key,
            manifest.bundle_ref,
            manifest.compatible_agent_contract,
            skill.version,
            kernel_skills::is_active(&manifest, skill),
            skill.supersedes.as_deref(),
            skill.identity_created_at_ms,
            skill.released_at_ms,
            skill.sandbox_expr(),
            source.to_string_lossy(),
        )
        .expect("format");
    }
    generated.push_str("    ]\n}\n");
    let disclosures = manifest
        .automatic_disclosures
        .iter()
        .map(|item| {
            format!(
                "    RuntimeAutomaticSkillDisclosure {{ snapshot_schema_version: {:?}, skill_key: {:?}, required_route_capability: {:?}, required_tool_capability: {:?} }},\n",
                item.snapshot_schema_version,
                item.skill_key,
                item.required_route_capability.as_deref(),
                item.required_tool_capability.as_deref(),
            )
        })
        .collect::<String>();
    write!(
        generated,
        "pub const OFFICIAL_AUTOMATIC_SKILL_DISCLOSURES: &[RuntimeAutomaticSkillDisclosure] = &[\n{disclosures}];\n\
         pub const OFFICIAL_AUTOMATIC_SKILL_DISCLOSURE_PROFILES: &[&[RuntimeAutomaticSkillDisclosure]] = &[OFFICIAL_AUTOMATIC_SKILL_DISCLOSURES];\n\
         fn product_release_specs() -> Vec<ProductRuntimeSkillSpecs> {{ vec![ProductRuntimeSkillSpecs {{ \
         product: musteragent_identity::ProductId::KERNEL, release_id: {:?}, digest: {:?}, \
         specs: compiled_runtime_skill_release_specs, disclosures: OFFICIAL_AUTOMATIC_SKILL_DISCLOSURES, \
         profiles: OFFICIAL_AUTOMATIC_SKILL_DISCLOSURE_PROFILES }}] }}\n",
        kernel_release::RELEASE_ID,
        digest,
    )
    .expect("format");
    let output = PathBuf::from(env::var_os("OUT_DIR").expect("build output"))
        .join("builtin_skill_releases.rs");
    fs::write(output, generated).expect("write builtin Skill releases");
}
