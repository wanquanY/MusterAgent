//! Compiles the kernel's generic base Skills from `contracts/kernel-skills.json`
//! into one catalog bound to the single kernel release. Hosts install further
//! Skills at runtime under their own product.
use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;

#[path = "../../../build-support/kernel_release.rs"]
mod kernel_release;
#[path = "../../../build-support/kernel_skills.rs"]
mod kernel_skills;

#[derive(Deserialize)]
struct SkillFrontmatter {
    title: Option<String>,
    description: String,
    when_to_use: String,
    #[serde(default, alias = "required_capabilities")]
    required_tools: Vec<String>,
    #[serde(default, alias = "optional_capabilities")]
    optional_tools: Vec<String>,
}

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("manifest directory"));
    let root = manifest_dir.join("../../..");
    let manifest = kernel_skills::load(&root);
    let digest = kernel_release::digest(&root);
    let capabilities = tool_capabilities(&root);

    let mut generated = String::from(
        "// @generated by crates/domains/skill/build.rs; do not edit.\n\
         fn generated_runtime_skill_specs() -> Vec<BuiltinSkillSpec> {\n    vec![\n",
    );
    for skill in &manifest.skills {
        emit_spec(&mut generated, &root, &manifest, skill, &capabilities);
    }
    generated.push_str("    ]\n}\n");
    generated.push_str(
        "fn generated_retained_catalog(_: &str) -> Option<(&'static str, Vec<BuiltinSkillSpec>)> { None }\n\
         fn generated_retained_catalog_base_refs() -> &'static [&'static str] { &[] }\n",
    );
    writeln!(
        generated,
        "fn compiled_skill_releases() -> Vec<product_catalog::CompiledSkillRelease> {{ vec![\
         product_catalog::CompiledSkillRelease {{ product: musteragent_identity::ProductId::KERNEL, \
         release_id: {:?}, digest: {:?}, active: true, profile_id: {:?}, \
         specs: generated_runtime_skill_specs, retained: generated_retained_catalog, \
         bases: generated_retained_catalog_base_refs }}] }}",
        kernel_release::RELEASE_ID,
        digest,
        kernel_release::PROFILE_ID,
    )
    .expect("format");
    let output = PathBuf::from(env::var_os("OUT_DIR").expect("build output"))
        .join("builtin_skill_catalog.rs");
    fs::write(output, generated).expect("write generated Skill catalog");
}

fn emit_spec(
    generated: &mut String,
    root: &Path,
    manifest: &kernel_skills::Manifest,
    skill: &kernel_skills::SkillRelease,
    capabilities: &BTreeMap<String, String>,
) {
    let (source, _) = skill.files(root);
    let instructions = fs::read_to_string(&source).expect("read Skill instructions");
    let frontmatter = parse_frontmatter(&instructions);
    let title = frontmatter
        .title
        .clone()
        .unwrap_or_else(|| markdown_title(&instructions));
    let surfaces = skill
        .surfaces
        .iter()
        .map(|surface| format!("Surface::{}", kernel_skills::surface_variant(surface)))
        .collect::<Vec<_>>()
        .join(", ");
    let lifecycle = if kernel_skills::is_active(manifest, skill) {
        "Active"
    } else {
        "Retired"
    };
    writeln!(
        generated,
        "        BuiltinSkillSpec {{\n\
         bundle_ref: {:?}, compatible_agent_contract: {:?},\n\
         skill_slot: {}, material_slot: {},\n\
         key: {:?}, title: {:?}, description: {:?}, when_to_use: {:?},\n\
         instructions: include_str!({:?}),\n\
         required_capabilities: &{:?}, optional_capabilities: &{:?},\n\
         surfaces: &[{surfaces}],\n\
         activation_policy: ActivationPolicy::{}, lifecycle: SkillLifecycle::{lifecycle},\n\
         sandbox: {},\n\
         }},",
        manifest.bundle_ref,
        manifest.compatible_agent_contract,
        skill.skill_slot(),
        skill.material_slot(),
        skill.skill_ref(),
        title,
        frontmatter.description,
        frontmatter.when_to_use,
        source.to_string_lossy(),
        resolve_capabilities(&frontmatter.required_tools, capabilities),
        resolve_capabilities(&frontmatter.optional_tools, capabilities),
        skill.activation(),
        skill.sandbox_expr(),
    )
    .expect("format");
}

// Skill frontmatter names executable Tools. Authorization uses the capability
// those Tools actually require; the two versioned keys need not be equal.
fn tool_capabilities(root: &Path) -> BTreeMap<String, String> {
    let document: serde_json::Value = serde_json::from_slice(
        &fs::read(root.join(kernel_release::KERNEL_TOOLS)).expect("kernel Tool manifest"),
    )
    .expect("parse kernel Tool manifest");
    let mut capabilities = BTreeMap::new();
    for deployment in ["cloud", "device"] {
        for tool in document["products"][kernel_release::PRODUCT][deployment]["tools"]
            .as_array()
            .expect("kernel Tools")
        {
            let key = tool["tool_key"].as_str().expect("Tool key").to_owned();
            let capability = tool["capability_key"]
                .as_str()
                .expect("capability key")
                .to_owned();
            if let Some(previous) = capabilities.insert(key.clone(), capability.clone()) {
                assert_eq!(
                    previous, capability,
                    "Tool {key} changes capability across deployments"
                );
            }
        }
    }
    capabilities
}

fn resolve_capabilities<'a>(
    tools: &[String],
    capabilities: &'a BTreeMap<String, String>,
) -> Vec<&'a str> {
    tools
        .iter()
        .map(|key| {
            capabilities
                .get(key)
                .unwrap_or_else(|| panic!("unknown Skill Tool {key}"))
                .as_str()
        })
        .collect()
}

fn parse_frontmatter(source: &str) -> SkillFrontmatter {
    let body = source
        .strip_prefix("---\n")
        .and_then(|value| value.split_once("\n---\n"))
        .map(|(frontmatter, _)| frontmatter)
        .expect("Skill instructions require YAML frontmatter");
    serde_yaml::from_str(body).expect("parse Skill frontmatter")
}

fn markdown_title(source: &str) -> String {
    source
        .lines()
        .find_map(|line| line.strip_prefix("# "))
        .filter(|title| !title.trim().is_empty())
        .map(str::to_owned)
        .expect("Skill instructions require a title or H1 heading")
}
