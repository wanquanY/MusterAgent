mod build_tool_table;
use build_tool_table::canonical_schema;
use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use std::path::PathBuf;

use serde::Deserialize;
use serde_json::Value;

#[path = "../../../build-support/kernel_release.rs"]
mod kernel_release;

const KERNEL_TOOLS: &str = kernel_release::KERNEL_TOOLS;
const SURFACES: [&str; 6] = ["web", "studio", "api", "desktop", "channel", "mobile"];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct KernelTools {
    schema_version: String,
    contains_credentials: bool,
    authority: Authority,
    dynamic_releases: Vec<serde_json::Value>,
    products: BTreeMap<String, BTreeMap<String, Deployment>>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Authority {
    rust_provider_id: String,
    backend_provider_id: String,
    default_policy_decision: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Deployment {
    head: String,
    tools: Vec<Tool>,
}

#[derive(Clone, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
struct Tool {
    tool_key: String,
    title: String,
    description: String,
    input_schema: Value,
    input_schema_sha256: String,
    output_schema: Value,
    output_schema_sha256: String,
    capability_key: String,
    target: Target,
    concurrency_class: String,
    idempotency: String,
    effect: String,
    approval: String,
    timeout_ms: u64,
    max_attempts: u32,
    required_scopes: Vec<String>,
    required_contexts: Vec<String>,
    data_classification: String,
    egress_policy: String,
    metadata: Metadata,
    surfaces: BTreeSet<String>,
}

#[derive(Clone, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
struct Target {
    owner: String,
    binding: String,
}

#[derive(Clone, Default, Deserialize, PartialEq)]
struct Metadata {
    artifact_type: Option<String>,
    sandbox_compatibility: String,
    wire_name: Option<String>,
    file_operation: Option<String>,
    file_identity_argument: Option<String>,
}

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("manifest directory"));
    let runtime_root = manifest_dir.join("../../..");
    let path = runtime_root.join(KERNEL_TOOLS);
    println!("cargo:rerun-if-changed={}", path.display());
    let source = fs::read(path).expect("kernel Tool manifest");
    let kernel: KernelTools = serde_json::from_slice(&source).expect("closed kernel Tool manifest");
    assert_eq!(kernel.schema_version, "musteragent.runtime.kernel-tools.v1");
    assert!(
        kernel.dynamic_releases.is_empty(),
        "the kernel catalog carries no dynamic capability releases"
    );
    assert!(
        !kernel.contains_credentials,
        "kernel Tool manifest must not contain credentials"
    );
    assert!(
        kernel
            .products
            .keys()
            .map(String::as_str)
            .eq([kernel_release::PRODUCT]),
        "kernel Tool manifest must contain exactly the kernel release"
    );
    let active = &kernel.products[kernel_release::PRODUCT];
    assert!(
        active.keys().map(String::as_str).eq(["cloud", "device"]),
        "kernel Tool manifest must cover Cloud and Device"
    );
    for deployment in active.values() {
        validate_catalog(&deployment.tools);
    }
    for value in [
        &kernel.authority.rust_provider_id,
        &kernel.authority.backend_provider_id,
    ] {
        value
            .parse::<musteragent_identity::CapabilityProviderId>()
            .expect("kernel Tool provider identity");
    }
    assert_ne!(
        kernel.authority.rust_provider_id, kernel.authority.backend_provider_id,
        "Rust and capability-provider identities must be distinct"
    );
    assert!(matches!(
        kernel.authority.default_policy_decision.as_str(),
        "allow" | "deny" | "require_approval"
    ));

    let mut generated =
        String::from("// @generated by crates/domains/tool/build.rs; do not edit.\n");
    generated.push_str(&format!(
        "pub const BUILTIN_RELEASE_PROFILE: &str = {:?};\n",
        kernel_release::PROFILE_ID
    ));
    for (name, deployment) in [
        ("BUILTIN_DEVICE_RELEASE_ID", "device"),
        ("BUILTIN_CLOUD_RELEASE_ID", "cloud"),
    ] {
        generated.push_str(&format!(
            "pub const {name}: &str = {:?};\n",
            active[deployment].head
        ));
    }
    generated.push_str(&format!(
        "pub const BUILTIN_SKILL_RELEASE_SCHEMA: &str = {:?};\n",
        kernel_release::SKILL_RELEASE_SCHEMA
    ));
    generated.push_str(&format!(
        "pub const BUILTIN_RUST_PROVIDER_ID: &str = {:?};\n",
        kernel.authority.rust_provider_id
    ));
    generated.push_str(&format!(
        "pub const BUILTIN_BACKEND_PROVIDER_ID: &str = {:?};\n",
        kernel.authority.backend_provider_id
    ));

    let catalogs = active
        .iter()
        .map(|(deployment, value)| ((kernel_release::PRODUCT, deployment.as_str()), value))
        .collect::<BTreeMap<_, _>>();
    build_tool_table::emit(&mut generated, &catalogs);
    for deployment in ["cloud", "device"] {
        generated.push_str(&format!(
            "fn compiled_raw_tools_{deployment}_current() -> Vec<RawTool> {{ {}() }}\n",
            build_tool_table::function(kernel_release::PRODUCT, deployment)
        ));
        generated.push_str(&format!(
            "const ACTIVE_{}_EXPECTED_TOOL_COUNT: usize = {};\n",
            deployment.to_ascii_uppercase(),
            build_tool_table::count(kernel_release::PRODUCT, deployment)
        ));
    }
    let digest = kernel_release::digest(&runtime_root);
    generated.push_str(&format!(
        "fn compiled_product_releases() -> &'static [product_release::CompiledProductRelease] {{ static RELEASES: &[product_release::CompiledProductRelease] = &[product_release::CompiledProductRelease {{ product: musteragent_identity::ProductId::KERNEL, release_id: {:?}, digest: {:?}, active: true, profile_id: {:?}, cloud_head: {:?}, device_head: {:?}, skill_schema: {:?}, cloud: cached_kernel_catalog!({}, {}), device: cached_kernel_catalog!({}, {}) }}]; RELEASES }}\n",
        kernel_release::RELEASE_ID,
        digest,
        kernel_release::PROFILE_ID,
        active["cloud"].head,
        active["device"].head,
        kernel_release::SKILL_RELEASE_SCHEMA,
        build_tool_table::function(kernel_release::PRODUCT, "cloud"),
        build_tool_table::count(kernel_release::PRODUCT, "cloud"),
        build_tool_table::function(kernel_release::PRODUCT, "device"),
        build_tool_table::count(kernel_release::PRODUCT, "device"),
    ));

    let output = PathBuf::from(env::var_os("OUT_DIR").expect("build output"))
        .join("builtin_tool_catalog.rs");
    fs::write(output, generated).expect("write compiled Tool catalog");
}

fn validate_catalog(tools: &[Tool]) {
    let keys = tools
        .iter()
        .map(|tool| tool.tool_key.as_str())
        .collect::<BTreeSet<_>>();
    let logical_keys = tools
        .iter()
        .map(|tool| logical_key(&tool.tool_key))
        .collect::<BTreeSet<_>>();
    let capabilities = tools
        .iter()
        .map(|tool| tool.capability_key.as_str())
        .collect::<BTreeSet<_>>();
    let logical_capabilities = tools
        .iter()
        .map(|tool| logical_key(&tool.capability_key))
        .collect::<BTreeSet<_>>();
    let wire_names = tools
        .iter()
        .map(|tool| {
            tool.metadata
                .wire_name
                .as_deref()
                .unwrap_or(tool.tool_key.as_str())
        })
        .collect::<BTreeSet<_>>();
    assert_eq!(
        keys.len(),
        tools.len(),
        "Tool catalog contains duplicate keys"
    );
    assert_eq!(
        logical_keys.len(),
        tools.len(),
        "Tool catalog contains multiple active versions of one logical Tool"
    );
    assert_eq!(
        capabilities.len(),
        tools.len(),
        "Tool catalog contains duplicate capabilities"
    );
    assert_eq!(
        logical_capabilities.len(),
        tools.len(),
        "Tool catalog contains multiple active versions of one logical Capability"
    );
    assert_eq!(
        wire_names.len(),
        tools.len(),
        "Tool catalog contains duplicate wire names"
    );
    for tool in tools {
        assert!(!tool.title.trim().is_empty(), "Tool title is empty");
        assert!(
            !tool.description.trim().is_empty(),
            "Tool description is empty"
        );
        assert!(
            !tool.surfaces.is_empty()
                && tool.surfaces.iter().all(|s| SURFACES.contains(&s.as_str())),
            "Tool surfaces are invalid: {}",
            tool.tool_key
        );
        // Every compiled Tool is projected into model requests as-is.
        assert_eq!(
            tool.input_schema.get("type").and_then(Value::as_str),
            Some("object"),
            "Tool input schema must declare a top-level object: {}",
            tool.tool_key,
        );
        assert!(
            matches!(
                tool.metadata.sandbox_compatibility.as_str(),
                "browser_compatible" | "server_required"
            ),
            "invalid sandbox compatibility for {}",
            tool.tool_key
        );
        canonical_schema(tool.input_schema.clone(), &tool.input_schema_sha256);
        canonical_schema(tool.output_schema.clone(), &tool.output_schema_sha256);
    }
}

fn logical_key(value: &str) -> &str {
    let (logical, version) = value
        .rsplit_once('@')
        .unwrap_or_else(|| panic!("versioned key has no release suffix: {value}"));
    assert!(
        !logical.is_empty()
            && !version.is_empty()
            && version.bytes().all(|byte| byte.is_ascii_digit())
            && version.parse::<u32>().is_ok_and(|value| value > 0),
        "versioned key is invalid: {value}"
    );
    logical
}
