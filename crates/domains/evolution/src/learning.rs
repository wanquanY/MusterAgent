use std::collections::BTreeSet;

use musteragent_content_ref::{ContentRef, Sha256};
use musteragent_identity::{
    AgentId, AgentVersionId, ContextBranchId, ConversationId, DreamJobId, LearningSignalId,
    LedgerOffset, LedgerRecordId, MemoryCollectionId, RunId, TenantId, UtcTimestamp, VersionNumber,
    VersionedKey,
};
use thiserror::Error;

/// Stable classification emitted by the deterministic end-of-run extractor.
#[derive(Debug, Copy, Clone, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub enum LearningSignalKind {
    UserInstruction,
    UserCorrection,
    ToolFailure,
    ToolSuccess,
    TaskOutcome,
    UserAcceptance,
    NegativeEvidence,
    Retraction,
}

/// Outcome carried by evidence; success eligibility is validated separately
/// from the textual claim generated by an induction model.
#[derive(Debug, Copy, Clone, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub enum LearningOutcome {
    Success,
    Failure,
    Cancelled,
    Interrupted,
    Unknown,
}

#[derive(Debug, Copy, Clone, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub enum RunTerminalEvidence {
    Completed,
    Failed,
    Cancelled,
    Interrupted,
}

#[derive(Debug, Copy, Clone, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub enum BranchEvidenceState {
    Active,
    Preserved,
    Abandoned,
}

/// Immutable, hash-attested source range. Summaries may discover this span,
/// but a publication evaluator must be able to re-read every listed record.
#[derive(Debug, Clone, Eq, PartialEq)]
pub struct EvidenceSpan {
    pub conversation_id: ConversationId,
    pub run_id: RunId,
    pub branch_id: Option<ContextBranchId>,
    pub branch_state: BranchEvidenceState,
    pub cursor_from: LedgerOffset,
    pub cursor_to: LedgerOffset,
    pub record_ids: Vec<LedgerRecordId>,
    pub record_hashes: Vec<Sha256>,
    pub terminal: RunTerminalEvidence,
    pub outcome: LearningOutcome,
}

impl EvidenceSpan {
    pub fn validate(&self) -> Result<(), LearningContractError> {
        if self.cursor_from.get() >= self.cursor_to.get()
            || self.record_ids.is_empty()
            || self.record_ids.len() != self.record_hashes.len()
            || self
                .record_ids
                .iter()
                .copied()
                .collect::<BTreeSet<_>>()
                .len()
                != self.record_ids.len()
        {
            return Err(LearningContractError::InvalidEvidenceSpan);
        }
        let terminal_matches = matches!(
            (self.terminal, self.outcome),
            (RunTerminalEvidence::Completed, LearningOutcome::Success)
                | (RunTerminalEvidence::Completed, LearningOutcome::Unknown)
                | (RunTerminalEvidence::Failed, LearningOutcome::Failure)
                | (RunTerminalEvidence::Cancelled, LearningOutcome::Cancelled)
                | (
                    RunTerminalEvidence::Interrupted,
                    LearningOutcome::Interrupted
                )
        );
        if !terminal_matches
            || (self.outcome == LearningOutcome::Success
                && self.branch_state != BranchEvidenceState::Active)
        {
            return Err(LearningContractError::IneligibleEvidence);
        }
        Ok(())
    }

    #[must_use]
    pub fn success_eligible(&self) -> bool {
        self.terminal == RunTerminalEvidence::Completed
            && self.outcome == LearningOutcome::Success
            && self.branch_state == BranchEvidenceState::Active
    }
}

#[derive(Debug, Clone, Eq, PartialEq)]
pub struct LearningSignal {
    pub signal_id: LearningSignalId,
    pub tenant_id: TenantId,
    pub target_agent_id: AgentId,
    pub kind: LearningSignalKind,
    pub evidence: Vec<EvidenceSpan>,
    pub extractor_version_ref: VersionedKey,
    pub policy_version_ref: VersionedKey,
    pub dedup_key: Sha256,
    pub created_at: UtcTimestamp,
}

impl LearningSignal {
    pub fn validate(&self) -> Result<(), LearningContractError> {
        if self.evidence.is_empty() {
            return Err(LearningContractError::MissingEvidence);
        }
        for span in &self.evidence {
            span.validate()?;
        }
        if matches!(
            self.kind,
            LearningSignalKind::ToolSuccess
                | LearningSignalKind::TaskOutcome
                | LearningSignalKind::UserAcceptance
        ) && !self.evidence.iter().all(EvidenceSpan::success_eligible)
        {
            return Err(LearningContractError::IneligibleSuccessSignal);
        }
        if self.dedup_key != self.canonical_dedup_key() {
            return Err(LearningContractError::DedupKeyMismatch);
        }
        Ok(())
    }

    #[must_use]
    pub fn canonical_dedup_key(&self) -> Sha256 {
        let mut bytes = b"musteragent.legacy.learning-signal.dedup.v1\0".to_vec();
        bytes.extend_from_slice(self.tenant_id.into_uuid().as_bytes());
        bytes.extend_from_slice(self.target_agent_id.into_uuid().as_bytes());
        bytes.push(signal_kind_code(self.kind));
        bytes.extend_from_slice(self.extractor_version_ref.as_str().as_bytes());
        bytes.push(0);
        bytes.extend_from_slice(self.policy_version_ref.as_str().as_bytes());
        for span in &self.evidence {
            bytes.extend_from_slice(span.conversation_id.into_uuid().as_bytes());
            bytes.extend_from_slice(span.run_id.into_uuid().as_bytes());
            match span.branch_id {
                Some(branch_id) => {
                    bytes.push(1);
                    bytes.extend_from_slice(branch_id.into_uuid().as_bytes());
                }
                None => bytes.push(0),
            }
            bytes.extend_from_slice(&span.cursor_from.get().to_be_bytes());
            bytes.extend_from_slice(&span.cursor_to.get().to_be_bytes());
            bytes.push(branch_state_code(span.branch_state));
            bytes.push(terminal_code(span.terminal));
            bytes.push(outcome_code(span.outcome));
            for (record_id, hash) in span.record_ids.iter().zip(&span.record_hashes) {
                bytes.extend_from_slice(record_id.into_uuid().as_bytes());
                bytes.extend_from_slice(&hash.into_bytes());
            }
        }
        Sha256::digest(bytes)
    }
}

#[derive(Debug, Copy, Clone, Eq, PartialEq)]
pub struct DreamWorkload {
    /// Evidence material capacity derived from the selected model's context
    /// window. This is context planning metadata, never a spend budget.
    pub evidence_context_tokens: u64,
    /// Structural payload guard for one private candidate submission. The
    /// normal Agent Loop, not this value, owns execution progress.
    pub candidate_batch_capacity: u16,
}

impl DreamWorkload {
    pub fn validate(self) -> Result<(), LearningContractError> {
        if self.evidence_context_tokens == 0
            || self.candidate_batch_capacity == 0
            || self.candidate_batch_capacity > 1_000
        {
            return Err(LearningContractError::InvalidDreamWorkload);
        }
        Ok(())
    }
}

#[derive(Debug, Copy, Clone, Eq, PartialEq)]
pub enum DreamJobStatus {
    Pending,
    Running,
    Completed,
    Failed,
    Cancelled,
}

/// Frozen Dream input identity. `input_manifest_ref` contains the exact list
/// of signal/evidence IDs at the frozen watermark; mutable "recent runs"
/// queries are forbidden after the Job is created.
#[derive(Debug, Clone, Eq, PartialEq)]
pub struct DreamJob {
    pub dream_job_id: DreamJobId,
    pub tenant_id: TenantId,
    pub target_agent_id: AgentId,
    pub agent_version_id: AgentVersionId,
    pub memory_collection_id: MemoryCollectionId,
    pub memory_collection_version: VersionNumber,
    pub ledger_watermark: LedgerOffset,
    pub input_manifest_ref: ContentRef,
    pub policy_version_ref: VersionedKey,
    pub growth_profile_ref: VersionedKey,
    pub growth_profile_hash: Sha256,
    /// Frozen manual-request generation watermark observed while scheduling
    /// this Job. The durable maximum prevents an already-observed request
    /// from being treated as new after restart.
    pub manual_request_generation: u64,
    pub model_route_ref: VersionedKey,
    /// SHA-256 identity of the exact credential-free model route selected by
    /// the control plane. A route alias alone is mutable and therefore cannot
    /// be the replay boundary for an autonomous learning job.
    pub model_route_hash: Sha256,
    /// Frozen per-attempt provider deadline budget. This is independent from
    /// the durable worker lease, which only protects queue ownership.
    pub model_timeout_ms: u64,
    pub workload: DreamWorkload,
    pub idempotency_key: Sha256,
    pub status: DreamJobStatus,
    pub retry_count: u16,
    pub lease_owner: Option<String>,
    pub lease_expires_at: Option<UtcTimestamp>,
    pub created_at: UtcTimestamp,
    pub completed_at: Option<UtcTimestamp>,
}

impl DreamJob {
    pub fn validate(&self) -> Result<(), LearningContractError> {
        self.workload.validate()?;
        if self.ledger_watermark.get() == 0
            || !(1_000..=3_600_000).contains(&self.model_timeout_ms)
            || self.idempotency_key != self.canonical_idempotency_key()
            || self.retry_count > 100
            || self
                .lease_owner
                .as_ref()
                .is_some_and(|owner| owner.is_empty())
            || self.lease_owner.is_some() != self.lease_expires_at.is_some()
            || (self.status == DreamJobStatus::Running && self.lease_owner.is_none())
            || (self.status != DreamJobStatus::Running && self.lease_owner.is_some())
            || (self.status == DreamJobStatus::Completed) != self.completed_at.is_some()
        {
            return Err(LearningContractError::InvalidDreamJob);
        }
        Ok(())
    }

    #[must_use]
    pub fn canonical_idempotency_key(&self) -> Sha256 {
        let mut bytes = b"musteragent.legacy.dream-job.idempotency.v1\0".to_vec();
        bytes.extend_from_slice(self.tenant_id.into_uuid().as_bytes());
        bytes.extend_from_slice(self.target_agent_id.into_uuid().as_bytes());
        bytes.extend_from_slice(self.agent_version_id.into_uuid().as_bytes());
        bytes.extend_from_slice(self.memory_collection_id.into_uuid().as_bytes());
        bytes.extend_from_slice(&self.memory_collection_version.get().to_be_bytes());
        bytes.extend_from_slice(&self.ledger_watermark.get().to_be_bytes());
        bytes.extend_from_slice(&self.input_manifest_ref.sha256.into_bytes());
        bytes.extend_from_slice(self.policy_version_ref.as_str().as_bytes());
        bytes.push(0);
        bytes.extend_from_slice(self.growth_profile_ref.as_str().as_bytes());
        bytes.extend_from_slice(&self.growth_profile_hash.into_bytes());
        bytes.extend_from_slice(&self.manual_request_generation.to_be_bytes());
        bytes.extend_from_slice(self.model_route_ref.as_str().as_bytes());
        bytes.extend_from_slice(&self.model_route_hash.into_bytes());
        bytes.extend_from_slice(&self.model_timeout_ms.to_be_bytes());
        Sha256::digest(bytes)
    }
}

const fn signal_kind_code(value: LearningSignalKind) -> u8 {
    match value {
        LearningSignalKind::UserInstruction => 1,
        LearningSignalKind::UserCorrection => 2,
        LearningSignalKind::ToolFailure => 3,
        LearningSignalKind::ToolSuccess => 4,
        LearningSignalKind::TaskOutcome => 5,
        LearningSignalKind::UserAcceptance => 6,
        LearningSignalKind::NegativeEvidence => 7,
        LearningSignalKind::Retraction => 8,
    }
}

const fn branch_state_code(value: BranchEvidenceState) -> u8 {
    match value {
        BranchEvidenceState::Active => 1,
        BranchEvidenceState::Preserved => 2,
        BranchEvidenceState::Abandoned => 3,
    }
}

const fn terminal_code(value: RunTerminalEvidence) -> u8 {
    match value {
        RunTerminalEvidence::Completed => 1,
        RunTerminalEvidence::Failed => 2,
        RunTerminalEvidence::Cancelled => 3,
        RunTerminalEvidence::Interrupted => 4,
    }
}

const fn outcome_code(value: LearningOutcome) -> u8 {
    match value {
        LearningOutcome::Success => 1,
        LearningOutcome::Failure => 2,
        LearningOutcome::Cancelled => 3,
        LearningOutcome::Interrupted => 4,
        LearningOutcome::Unknown => 5,
    }
}

#[derive(Debug, Error, Copy, Clone, Eq, PartialEq)]
pub enum LearningContractError {
    #[error("Learning evidence span is structurally invalid")]
    InvalidEvidenceSpan,
    #[error("Learning evidence is not eligible for its claimed outcome")]
    IneligibleEvidence,
    #[error("Learning signal has no immutable evidence")]
    MissingEvidence,
    #[error("success Learning signal contains non-success evidence")]
    IneligibleSuccessSignal,
    #[error("Learning signal dedup key does not match its frozen evidence")]
    DedupKeyMismatch,
    #[error("Dream budget is outside the supported bounds")]
    InvalidDreamWorkload,
    #[error("Dream Job frozen state is invalid")]
    InvalidDreamJob,
}
